def about(run: dict) -> str:
    """Where the report came from: plugin, version, project page and date."""
    from . import __version__
    when = time.strftime("%d %b %Y %H:%M", time.localtime(run.get("created") or time.time()))
    return (f"Generated by {PRODUCT} {__version__}, a plugin for Hermes Agent, on {when} (run {run['id']}). "
            f"Project page: {PROJECT_URL}")


# ── deliberation (shared by the PDF and Markdown reports) ──────────────────

SKIP_TEXT = {"no material disagreement": "the seats had no material disagreement",
             "same action": "the seats recommended the same action (setting: only on the action)",
             "time": "there was not enough time left", "budget": "there was not enough budget left",
             "agenda failed": "the chairman could not list the disputed points"}
STANCE_WORD = {"hold": "held", "change": "changed", "partly": "partly changed"}


def delib_last(d: dict, seat: str, did: str) -> Optional[dict]:
    """A seat's latest reply on one point, over all rounds."""
    last = None
    for rnd in d.get("rounds") or []:
        for x in (rnd.get("replies", {}).get(seat) or {}).get("responses") or []:
            if x.get("dispute") == did:
                last = x
    return last


def delib_decided(chair: dict, disputes: Optional[list] = None) -> dict:
    """The chairman's call per dispute id (matched by id, wording or order, so older runs work too)."""
    from .engine import match_resolved
    return match_resolved(chair.get("disputes_resolved") or [], disputes or [])


_NEEDS_CITE = re.compile(r"\b(?:with|in|see|per|from|by|of|to|under|on|and|or)$", re.I)
_CITES = re.compile(r"\s*\[(?:[EI]\d+(?:\s*[,;–-]\s*)?)+\]")


def _clean(text: str) -> str:
    """Plain sentence text: no markdown, no citations."""
    t = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", str(text or ""))
    t = _CITES.sub(lambda m: m.group(0) if _NEEDS_CITE.search(t[: m.start()]) else "", t)
    t = re.sub(r"[*_`#>]+", "", t)
    return re.sub(r"\s+", " ", t).strip()


def _sentences(text: str, n: int, limit: int) -> str:
    parts = re.split(r"(?<=[.!?])\s+(?=[A-Z0-9“\"(])", _clean(text))
    out = ""
    for p in parts[:n]:
        if len(out) + len(p) > limit and out:
            break
        out = f"{out} {p}".strip()
    return out if len(out) <= limit else out[: limit - 1].rstrip() + "…"


def exec_summary(run: dict) -> dict:
    """What the executive-summary page shows. The chairman writes the bottom line and reasons; when it did not
    (older runs, a plain-text verdict) they are assembled from the verdict, and 'assembled' says so."""
    from .followup import name_chair
    chair = run.get("chair") or {}
    ok = chair.get("status") == "ok"
    if ok:
        chair = name_chair(chair, run.get("seats") or [])
    es = chair.get("executive_summary") or {}
    out = {"ok": ok, "decision": chair.get("decision") if ok else None,
           "confidence": (chair.get("confidence") or "not stated") if ok else None,
           "error": None if ok else (run.get("error") or "The chairman did not deliver a verdict."),
           "assembled": False}
    if not ok:
        return out
    bottom = _clean(es.get("bottom_line"))
    if not bottom:
        out["assembled"] = True
        paras = [p for p in str(chair.get("final_answer") or "").split("\n\n")
                 if p.strip() and not p.lstrip().startswith(("#", "|", "-", "*", "1."))]
        bottom = _sentences(paras[0] if paras else chair.get("confidence_note") or "", 3, 480)
    reasons = [_clean(r) for r in es.get("reasons") or [] if _clean(r)][:3]
    if not reasons:
        out["assembled"] = True
        reasons = [_sentences(a, 1, 220) for a in chair.get("agreement") or []][:3]
    change = _clean(es.get("change"))
    if run.get("follow_of") and not change and chair.get("change_from_earlier"):
        change = _sentences(chair["change_from_earlier"], 1, 220)
    acts = chair.get("next_actions") or []
    d = run.get("deliberation") or {}
    answered = sum(1 for a in (run.get("answers") or {}).values() if a.get("status") == "ok")
    stood = [f"{answered} of {len(run.get('seats') or [])} seats answered"]
    if chair.get("dissent"):
        k = len(chair["dissent"])
        stood.append(f"{k} dissent{'s' if k != 1 else ''} on record")
    else:
        stood.append("no dissent recorded")
    if d.get("rounds"):
        k, still = len(d.get("disputes") or []), len(d.get("open") or [])
        stood.append(f"debated {k} point{'s' if k != 1 else ''}" + (f", {still} still disputed" if still else ", all settled"))
    rk = run.get("ranking") or []
    if rk:
        top = next((s["name"] for s in run.get("seats") or [] if s["label"] == rk[0]["label"]), None)
        if top:
            stood.append(f"{top} ranked first by its peers")
    out.update(bottom_line=bottom, reasons=reasons, change=change if run.get("follow_of") else "",
               actions=[_clean(a) for a in acts[:3]], more_actions=max(0, len(acts) - 3),
               reverse=[_clean(r) for r in (chair.get("reverse_if") or [])[:2]], stood=stood)
    return out


def kept_side(m: dict) -> bool:
    return bool(m.get("kept_side", m.get("from") is not None and m.get("from") == m.get("to")))


def stance_word(r: Optional[dict], start_side: str) -> str:
    """'conceded a point' when a seat partly moved but stayed on its side."""
    if not r:
        return "no reply"
    if r.get("stance") in ("partly", "change") and r.get("side") == start_side:
        return "conceded a point"
    return STANCE_WORD.get(r.get("stance"), "no reply")


def move_text(m: dict) -> str:
    if kept_side(m):
        return f"{m['seat']} on {m['dispute']} (round {m['round']}): kept “{m['from']}” but conceded a point. {m['because']}"
    return f"{m['seat']} on {m['dispute']} (round {m['round']}): {m['from']} → {m['to']}. {m['because']}"


def delib_line(run: dict) -> str:
    """One sentence for the summary page ('' when the run had no deliberation)."""
    d = run.get("deliberation") or {}
    if d.get("rounds"):
        n, mv = len(d.get("disputes") or []), d.get("moves") or []
        s = f"The seats deliberated on {n} disputed point{'s' if n != 1 else ''}"
        s += f" over {len(d['rounds'])} rounds" if len(d["rounds"]) > 1 else ""
        if mv:
            s += "; " + "; ".join(f"{m['seat']} {'conceded a point on' if kept_side(m) else 'changed its view on'} "
                                  f"{m['dispute']}" for m in mv[:3])
            s += " and more" if len(mv) > 3 else ""
        else:
            s += "; nobody changed position"
        open_ = d.get("open") or []
        if open_:
            s += f"; {', '.join(open_)} stayed disputed"
        return s + "."
    if d.get("skipped") and d["skipped"] != "off":
        return f"No deliberation: {SKIP_TEXT.get(d['skipped'], d['skipped'])}."
    return ""


DISCLAIMER = ("Advisory output from multiple AI models. It is not professional, engineering, legal, medical "
              "or financial approval. Check the reasoning and evidence before acting on it.")


def _date(ts: float) -> str:
    return time.strftime("%Y-%m-%d %H:%M", time.localtime(ts))


def _bullets(items: list[str]) -> str:
    return "\n".join(f"- {i}" for i in items) if items else "_None recorded._"


def _cell(text: Any) -> str:
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ")


def _conf(v: Any) -> str:
    return f"{v:.2f}" if isinstance(v, (int, float)) else "n/a"


def ranking_matrix(run: dict[str, Any]) -> tuple[list[str], list[list[str]]]:
    """Rows are reviewers, columns the answers they ranked; both shown by seat name."""
    name = {s["label"]: s["name"] for s in run["seats"]}
    labels = [s["label"] for s in sorted(run["seats"], key=lambda s: s["label"])
              if run["answers"].get(s["label"], {}).get("status") == "ok"]
    rows = []
    for rev in labels:
        r = run["reviews"].get(rev) or {}
        if r.get("status") != "ok":
            rows.append([name[rev]] + ["–"] * len(labels))
            continue
        rows.append([name[rev]] + [str(r["ranking"].index(lab) + 1) if lab in r["ranking"] else "–" for lab in labels])
    return [name[x] for x in labels], rows


def _evidence_lines(run: dict) -> list[str]:
    """Method lines about the evidence files and who saw the pictures."""
    files = run.get("files") or []
    if not files:
        return []
    idx = run.get("evidence_index") or {}
    out = [f"Evidence files: {len(files)}, about {idx.get('tokens', 0):,} tokens in each call"]
    imgs = idx.get("images") or []
    if imgs:
        seeing = [s["name"] for s in run["seats"] if s.get("sees_images")]
        by = next((i.get("described_by") for i in imgs if i.get("described_by")), None)
        out.append(f"Pictures: {len(imgs)}; seen directly by {', '.join(seeing) or 'no seat'}; "
                   + (f"described by {by} for the other seats, the blind vote and the chairman"
                      if by else "no description could be written"))
    return out


def _files_rows(run: dict) -> list[list[str]]:
    rows = []
    for f in run.get("files") or []:
        size = f"{(f.get('size') or 0) / 1024:,.0f} KB"
        rows.append([f.get("name") or "", f.get("kind") or "", size, f"{f.get('tokens') or 0:,}",
                     "; ".join(f.get("notes") or [])])
    return rows


def _cost_lines(run: dict) -> list[str]:
    """Estimated cost (tokens × list price), the budget, and the caveats that apply to this run."""
    from .pricing import fmt, limit
    u = usage_totals(run)
    if u.get("est_charged") is None:
        return []
    out = [f"Estimated cost: {fmt(u['est_charged'])}"
           + (f" (at list price, including subscription seats: {fmt(u['est_list'])})" if u["est_list"] > u["est_charged"] else "")
           + "; token counts × list price for pay-per-use seats (subscription seats are not counted), not a provider bill"]
    lim = limit(run)
    from .insights import limit_changes
    out.append(f"Budget: {fmt(lim)}" if lim else "Budget: none")
    if limit_changes(run, "usd"):
        out[-1] += f" ({limit_changes(run, 'usd')})"
    if (run.get("skipped") or {}).get("review") == "budget":
        out[-1] += " — the blind vote was skipped to stay within it"
    if run.get("budget_tokens"):
        out[-1] += f"; answers were limited to {run['budget_tokens']:,} output tokens to fit"
    if u.get("est_unknown_calls"):
        out.append(f"{u['est_unknown_calls']} call(s) on models with no known price are not counted")
    if u.get("abandoned"):
        out.append(f"{u['abandoned']} call(s) cut off by the time limit are counted at their maximum cost")
    return out


def _stage_cost_rows(run: dict) -> list[list[str]]:
    from .pricing import fmt
    names = {"describe": "Picture descriptions", "stage1": "Answers", "review": "Blind vote", "chair": "Chairman"}
    rows = []
    for st, label in names.items():
        calls = [c for c in run.get("usage") or [] if c.get("stage") == st]
        if calls:
            rows.append([label, str(len(calls)), f"{sum(c.get('input_tokens') or 0 for c in calls):,}",
                         f"{sum(c.get('output_tokens') or 0 for c in calls):,}",
                         fmt(sum(c.get("cost_est") or 0 for c in calls)), fmt(sum(c.get("cost_list") or 0 for c in calls))])
    return rows


def _limits_line(run: dict) -> str:
    secs = (run.get("limits") or {}).get("max_secs")
    from .insights import limit_changes
    out = f"Time limit for the whole run: {secs / 60:g} min" if secs else "Time limit for the whole run: none"
    if limit_changes(run, "time"):
        out += f" ({limit_changes(run, 'time')})"
    if (run.get("skipped") or {}).get("review") == "time":
        out += " — the blind vote was skipped to stay within it"
    secs_run = run_seconds(run)
    if secs_run:
        out += f"; actual run time {int(secs_run // 60)} min {int(secs_run % 60)} s"
    return out


def _seat_name(run: dict, label: str) -> str:
    """A dissent's seat by name, whatever form the chairman's label took."""
    from .followup import seat_of
    lab = seat_of(label, run.get("seats") or [])
    s = next((x for x in run.get("seats") or [] if x.get("label") == lab), None)
    return s["name"] if s else str(label or "A seat")


def run_seconds(run: dict) -> float:
    """From opening to the last recorded event (the verdict, a failure or a stop)."""
    tl = run.get("timeline") or []
    return max(0.0, tl[-1]["t"] - run["created"]) if tl and run.get("created") else 0.0


def render(run: dict[str, Any]) -> str:
    chair = run.get("chair") or {}
    ok_chair = chair.get("status") == "ok"
    if ok_chair:
        from .followup import name_chair
        chair = name_chair(chair, run.get("seats") or [])
    rank = {r["label"]: r for r in run.get("ranking") or []}
    out: list[str] = []
    out.append(f"# Committee report: {run.get('title') or run['question'].splitlines()[0][:150]}")
    if run.get("title"):
        out.append(f"**Question:** {run['question']}")
    out.append(f"{run['template_title']} · {_date(run['created'])} · run `{run['id']}` · status **{run['status']}**")
    if run.get("follow_of"):
        prev = run.get("follow_prev") or {}
        out.append(f"Follow-up to run `{run['follow_of']}`: the seats were given its verdict as background.")
        if prev.get("decision") or chair.get("change_from_earlier"):
            out.append("## What changed since the earlier run\n" + _bullets([x for x in (
                f"**Earlier** ({prev.get('confidence') or 'not stated'} confidence): {prev['decision']}" if prev.get("decision") else "",
                f"**Now** ({chair.get('confidence') or 'not stated'} confidence): {chair.get('decision')}" if ok_chair else "",
                f"**Why:** {chair['change_from_earlier']}" if chair.get("change_from_earlier") else "") if x]))
    if run.get("error"):
        out.append(f"> **Incomplete run:** {run['error']}")

    es = exec_summary(run)
    if es["ok"]:
        lines = ["## Executive summary", f"**Decision:** {es['decision'] or '—'} _(confidence: {es['confidence']})_"]
        if es.get("change"):
            lines.append(f"**Since the earlier run:** {es['change']}")
        lines.append(es["bottom_line"])
        if es["reasons"]:
            lines.append("**Why:**\n" + _bullets(es["reasons"]))
        if es["actions"]:
            lines.append("**Do next:**\n" + "\n".join(f"{i}. {a}" for i, a in enumerate(es["actions"], 1))
                         + (f"\n\n_{es['more_actions']} more in the full list below._" if es["more_actions"] else ""))
        if es["reverse"]:
            lines.append("**What would change this:**\n" + _bullets(es["reverse"]))
        lines.append("_" + " · ".join(es["stood"]) + "_")
        out.append("\n\n".join(lines))

    out.append("## Verdict")
    if ok_chair:
        out.append(f"**Decision:** {chair['decision'] or '—'}")
        conf = chair.get("confidence") or "not stated"
        out.append(f"**Confidence:** {conf}" + (f". {chair['confidence_note']}" if chair.get("confidence_note") else ""))
        if chair.get("reverse_if"):
            out.append("**Would reverse if:**\n" + _bullets(chair["reverse_if"]))
        if delib_line(run):
            out.append(f"_{delib_line(run)}_")
        out.append("## Final answer\n" + chair["final_answer"])
    else:
        out.append("_No chairman verdict. The individual answers below are the committee's output._")

    out.append("## Roster")
    out.append("| Seat | Model | Answered | Confidence | Avg peer place |\n|---|---|---|---|---|")
    for s in sorted(run["seats"], key=lambda s: s["label"]):
        a = run["answers"].get(s["label"]) or {}
        r = rank.get(s["label"])
        avg = "%.2f" % r["avg_rank"] if r else "–"
        out.append(f"| {_cell(s['name'])} | {_cell(model_label(s))} | {'yes' if a.get('status') == 'ok' else a.get('status', 'not run')} | "
                   f"{_conf(a.get('confidence'))} | {avg} |")
    out.append(f"Chairman: {model_label(run['chairman'])}")
    out.append(f"_Chairman's brief{' (custom)' if run.get('custom_brief') else ''}: {run.get('chairman_guidance') or '—'}"
               f"{' · Mode: decision' if run.get('decision_focus') else ' · Mode: answer'}_")

    if run.get("reviews"):
        labels, rows = ranking_matrix(run)
        out.append("## Peer ranking\nEach reviewer saw anonymous responses in a shuffled order. "
                   "1 = best. Rows are reviewers, columns are the responses they ranked.")
        out.append("| Reviewer | " + " | ".join(labels) + " |\n|---|" + "---|" * len(labels))
        out.extend("| " + " | ".join(r) + " |" for r in rows)
        if run.get("ranking"):
            nm = {s["label"]: s["name"] for s in run["seats"]}
            out.append("**Overall:** " + ", ".join(
                f"{nm.get(r['label'], r['label'])} ({r['avg_rank']:.2f}, {r['first_votes']} first)" for r in run["ranking"]))

    d = run.get("deliberation") or {}
    if d.get("rounds"):
        decided = delib_decided(chair, d["disputes"])
        out.append("## Deliberation\n" + (d.get("reason") or ""))
        for p in d["disputes"]:
            lines = [f"### {p['id']} · {p['point']}", f"_{'About the action' if p['level'] == 'action' else 'About a claim the decision rests on' if p['level'] == 'claim' else 'Emphasis'}_"]
            for pos in p["positions"]:
                r = delib_last(d, pos["seat"], p["id"])
                moved = f" → {r['side']}" if r and r.get("side") and r["side"] != pos["side"] else ""
                word = stance_word(r, pos["side"])
                extra = [x for x in (r or {}).get("evidence") or []
                         if not re.search(rf"\b{re.escape(x)}\b", (r or {}).get("argument") or "")]
                ev = f" [{', '.join(extra)}]" if extra else ""
                lines.append(f"- **{pos['seat']}** ({pos['side']}{moved}, {word}): {(r or {}).get('argument') or pos['view']}{ev}")
            x = decided.get(p["id"])
            if x:
                lines.append(f"\n**Chairman's call:** {x['decided']}" + (f" Decided by: {x['by_argument']}" if x.get("by_argument") else ""))
            out.append("\n".join(lines))
        if d.get("moves"):
            out.append("**Who changed their mind:**\n" + _bullets([move_text(m) for m in d["moves"]]))
    elif delib_line(run):
        out.append("## Deliberation\n" + delib_line(run))

    if ok_chair:
        out.append("## Agreement\n" + _bullets(chair.get("agreement") or []))
        out.append("## Dissent kept on record")
        if chair.get("dissent"):
            out.extend(f"- **{_seat_name(run, d['label'])}:** {d['view']}" for d in chair["dissent"])
        else:
            out.append("_No dissent recorded._")
        out.append("## Open questions\n" + _bullets(chair.get("open_questions") or []))
        out.append("## Next actions\n" + _bullets(chair.get("next_actions") or []))

    out.append("## Seat answers")
    for s in sorted(run["seats"], key=lambda s: s["label"]):
        a = run["answers"].get(s["label"]) or {}
        out.append(f"### {s['name']} ({model_label(s)})")
        if s.get("instructions"):
            out.append(f"_Instructions:_ {s['instructions']}")
        if a.get("status") != "ok":
            out.append(f"**Did not answer:** {a.get('error', 'not run')}")
            continue
        out.append(f"**Position:** {a.get('summary') or '—'}  \n**Confidence:** {_conf(a.get('confidence'))}"
                   + ("  \n_Answer returned as plain text (structured output failed)._" if a.get("fallback") else ""))
        for title, key in (("Key points", "key_points"), ("Assumptions", "assumptions"), ("Risks", "risks"),
                           ("Evidence it would need", "evidence_gaps")):
            if a.get(key):
                out.append(f"**{title}:**\n" + _bullets(a[key]))
        if a.get("would_change_mind"):
            out.append(f"**Would change its mind if:** {a['would_change_mind']}")
        crit = [e for r in run["reviews"].values() if r.get("status") == "ok"
                for e in r.get("evaluations") or [] if e["label"] == s["label"]]
        if crit:
            out.append("**Peer critiques received:**\n" + "\n".join(
                f"- Strengths: {e['strengths'] or '—'} Weaknesses: {e['weaknesses'] or '—'}" for e in crit))
        out.append("<details><summary>Full answer</summary>\n\n" + a["answer"] + "\n\n</details>")

    u = usage_totals(run)
    cost = (f"${u['cost_usd']:.4f}" if u["cost_usd"] is not None
            else "unknown (the providers did not report cost)" + (" — partial figures only" if u["cost_partial"] else ""))
    out.append("## Method and usage")
    out.append(_bullets([
        f"Template: {run['template_title']}" + (f", preset `{run['preset']}`" if run.get("preset") else ""),
        f"Stages: independent answers → {'anonymous peer ranking → ' if run['review'] else ''}chairman synthesis",
        f"Quorum: {run['quorum']} of {len(run['seats'])} seats; stage time limit {run['stage_timeout']} s",
        _limits_line(run),
        *_evidence_lines(run),
        *_cost_lines(run),
        f"Model calls: {u['calls']}; tokens in {u['input_tokens'] or 'n/a'}, out {u['output_tokens'] or 'n/a'}; provider-reported cost {cost}",
    ] + [f"Warning: {w}" for w in run.get("warnings") or []]))
    rows = _stage_cost_rows(run)
    if rows:
        out.append("| Stage | Calls | Tokens in | Tokens out | Est. cost | At list price |\n|---|---|---|---|---|---|\n"
                   + "\n".join("| " + " | ".join(r) + " |" for r in rows))
    from .followup import own_brief
    brief = own_brief(run)
    if brief or run.get("evidence") or run.get("files"):
        out.append("## Appendix: brief and evidence")
        if brief:
            out.append("### Brief\n" + brief)
        if run.get("evidence"):
            out.append("### Evidence pack\n" + run["evidence"])
        if run.get("files"):
            rows = _files_rows(run)
            out.append("### Evidence files\nThe seats cite these as [E1], [E2]… (text) and [I1], [I2]… (pictures). "
                       "The extracted text is kept in the run folder (evidence/sections.json).\n\n"
                       "| File | Type | Size | Tokens | Notes |\n|---|---|---|---|---|\n"
                       + "\n".join("| " + " | ".join(c.replace("|", "/") for c in r) + " |" for r in rows))
            imgs = (run.get("evidence_index") or {}).get("images") or []
            if imgs:
                out.append("### Pictures\n" + "\n\n".join(
                    f"**[{i['id']}] {i['source']}" + (f" · {i['locator']}" if i.get('locator') else "") + "**  \n"
                    + (i.get("description") or f"_Not described: {i.get('describe_error') or 'unknown'}_")
                    for i in imgs))
    out.append("---\n_" + DISCLAIMER + "_")
    out.append("---\n_" + about(run) + "_")
    return "\n\n".join(out) + "\n"
