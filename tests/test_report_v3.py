"""The report shows seats by name, keeps a follow-up's background out of the appendix, and links citations."""
import random
import threading

import pytest

from committee import config as c
from committee import engine as e
from committee import followup, report_md


def _run(settings, fake_llm):
    run = e.new_run(c.build_roster(settings), question="Gearbox?", rng=random.Random(4))
    llm = fake_llm()
    while run["next_stage"]:
        e.advance(run, llm, threading.Event(), lambda _m: None)
    return run


def test_dissent_labels_resolve_to_seat_names():
    seats = [{"label": "A", "name": "Brand-2.5"}, {"label": "B", "name": "Model-6"}, {"label": "C", "name": "Lab-Fast"}]
    for raw, want in (("Response A (Brand-2.5)", "A"), ("C", "C"), ("Lab-Fast", "C"), ("response b", "B"),
                      ("Response A (Lab-Fast)", "C"), ("nobody", "")):
        assert followup.seat_of(raw, seats) == want, raw
    chair = followup.name_chair({"dissent": [{"label": "Response A (Brand-2.5)", "view": "Response B is wrong."}],
                                 "change_from_earlier": "Response C changed its view."}, seats)
    assert chair["dissent"][0]["name"] == "Brand-2.5" and "Model-6 is wrong" in chair["dissent"][0]["view"]
    assert chair["change_from_earlier"] == "Lab-Fast changed its view."


def test_follow_up_background_is_not_repeated_as_the_brief():
    prev = {"id": "r1", "question": "Run or swap?", "chair": {"status": "ok", "decision": "Swap", "confidence": "medium",
                                                              "final_answer": "Because."}}
    brief = followup.context(prev) + "\n\nThe user's own brief."
    assert followup.own_brief({"follow_of": "r1", "brief": brief}) == "The user's own brief."
    assert followup.own_brief({"brief": "Plain brief."}) == "Plain brief."
    assert followup.prev_summary(prev)["decision"] == "Swap"


def test_markdown_report_names_seats_not_letters(settings, fake_llm):
    run = _run(settings, fake_llm)
    lab = run["seats"][0]["label"]
    run["chair"]["dissent"] = [{"label": f"Response {lab} ({run['seats'][0]['name']})", "view": "Disagrees."}]
    md = report_md.render(run)
    assert "Response Response" not in md and f"**{run['seats'][0]['name']}:** Disagrees." in md
    assert "| Seat | Model | Answered |" in md


def test_pdf_has_bookmarks_and_citation_links(settings, fake_llm, tmp_path):
    fitz = pytest.importorskip("fitz")
    from committee import report_pdf
    run = _run(settings, fake_llm)
    run["files"] = [{"name": "note.txt", "kind": "text", "size": 2048, "tokens": 40, "notes": []}]
    run["evidence_index"] = {"tokens": 40, "images": [], "sections": [{"id": "E1", "source": "note.txt", "locator": ""}]}
    run["chair"]["next_actions"] = ["Check the gearbox [E1]."]
    out = report_pdf.render(run, tmp_path / "r" / "report.pdf")
    doc = fitz.open(str(out))
    toc = [t[1] for t in doc.get_toc()]
    assert toc[:3] == ["Executive summary", "Decision in detail", "The committee"] and "Appendix B · Evidence" in toc
    ev_page = next(t[2] for t in doc.get_toc() if t[1] == "Appendix B · Evidence")
    links = [lk for p in list(doc)[1:] for lk in p.get_links()]          # citations, after the summary page
    assert links and all(lk.get("page") == ev_page - 1 for lk in links)
    starts = {t[2] - 1 for t in doc.get_toc()}
    assert {lk.get("page") for lk in doc[0].get_links()} <= starts       # page 1 contents point at section starts
    text = doc[0].get_text()
    assert "Response A" not in text and "[[" not in text


def test_reports_say_where_they_came_from(settings, fake_llm, tmp_path):
    fitz = pytest.importorskip("fitz")
    from committee import __version__, report_pdf
    run = _run(settings, fake_llm)
    assert f"Hermes Committee {__version__}" in report_md.render(run)
    doc = fitz.open(str(report_pdf.render(run, tmp_path / "r" / "report.pdf")))
    assert doc[0].get_text().startswith("HERMES COMMITTEE")
    assert all(p.get_text().startswith("Hermes Committee") for p in list(doc)[1:])
    assert f"Generated by Hermes Committee {__version__}" in doc[-1].get_text().replace("\n", " ")
    assert doc.metadata["creator"].startswith("Hermes Committee")
